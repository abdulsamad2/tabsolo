  onBulkShortcut: (listener) => ipcRenderer.on('bulk-shortcut', (_event, name) => listener(name)),
  onOpenPalette: (listener) => ipcRenderer.on('open-palette', () => listener()),
  recentNotices: () => ipcRenderer.invoke('notices:recent'),
  onPromptWatch: (listener) => ipcRenderer.on('prompt-watch', (_event, info) => listener(info)),
  getShortcuts: () => ipcRenderer.invoke('shortcuts:get'),
  setShortcut: (id, accelerator) => ipcRenderer.invoke('shortcuts:set', { id, accelerator }),
  resetShortcuts: () => ipcRenderer.invoke('shortcuts:reset'),
  onShortcutsChanged: (listener) => ipcRenderer.on('shortcuts-changed', (_event, info) => listener(info)),
  checkAccountHealth: () => ipcRenderer.invoke('accounts:health-check'),
