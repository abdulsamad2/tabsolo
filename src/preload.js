  stopRecording: (options) => ipcRenderer.invoke('recorder:stop', options ?? {}),
  recorderStatus: () => ipcRenderer.invoke('recorder:status'),
  listPlaybooks: () => ipcRenderer.invoke('playbooks:list'),
  saveLastRecordingAsPlaybook: (payload) => ipcRenderer.invoke('playbooks:save-from-last-recording', payload ?? {}),
  readPlaybook: (id) => ipcRenderer.invoke('playbooks:read', id),
  deletePlaybook: (id) => ipcRenderer.invoke('playbooks:delete', id),
  renamePlaybook: (payload) => ipcRenderer.invoke('playbooks:rename', payload),
  runPlaybook: (payload) => ipcRenderer.invoke('playbooks:run', payload),
